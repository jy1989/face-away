def resolve_language(preference: str = "auto", system_ui_languages=None) -> str:
    """Chinese system UI -> Chinese; all other UI languages -> English.

    Manual preference overrides detection. Unknown preference is auto.
    """
    if preference in ("zh", "en"):
        return preference
    if system_ui_languages is None:
        system_ui_languages = QLocale.system().uiLanguages()
    primary = (system_ui_languages or ["en"])[0]
    return "zh" if primary.replace("_", "-").lower().startswith("zh") else "en"


def translate(language: str, key: str, **variables) -> str:
    text = MESSAGES.get(language, MESSAGES["en"]).get(key)
    if text is None:
        raise KeyError(f"Untranslated UI key: {language}/{key}")
    return text.format(**variables)
